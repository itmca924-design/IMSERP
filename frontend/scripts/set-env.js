const fs = require('fs');
const path = require('path');

// 1. Locate .env file
const envPathCandidates = [
  path.join(__dirname, '..', '.env'),
  path.join(__dirname, '..', '..', '.env')
];

let envContent = '';
for (const p of envPathCandidates) {
  if (fs.existsSync(p)) {
    envContent = fs.readFileSync(p, 'utf8');
    break;
  }
}

// 2. Parse key-value pairs from .env
const envVars = {};
if (envContent) {
  envContent.split(/\r?\n/).forEach(line => {
    const trimmed = line.trim();
    if (trimmed && !trimmed.startsWith('#')) {
      const idx = trimmed.indexOf('=');
      if (idx !== -1) {
        const key = trimmed.substring(0, idx).trim();
        let val = trimmed.substring(idx + 1).trim();
        // Remove enclosing quotes if any
        if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
          val = val.slice(1, -1);
        }
        envVars[key] = val;
      }
    }
  });
}

const API_BASE_URL = envVars.API_BASE_URL || 'http://localhost:5000';
const API_URL = envVars.API_URL || `${API_BASE_URL}/api`;
const BIOMETRIC_WEBHOOK_URL = envVars.BIOMETRIC_WEBHOOK_URL || `${API_URL}/attendance/biometric/hikvision`;

console.log(`[IMSERP ENV] Syncing configuration:`);
console.log(`  - API_BASE_URL:          ${API_BASE_URL}`);
console.log(`  - API_URL:               ${API_URL}`);
console.log(`  - BIOMETRIC_WEBHOOK_URL: ${BIOMETRIC_WEBHOOK_URL}`);

// 3. Generate src/assets/env.js
const envJsContent = `(function (window) {
  window.__env = window.__env || {};
  var isLocal = typeof window !== 'undefined' && (window.location.hostname === 'localhost' || window.location.hostname === '127.0.0.1') && window.location.port !== '80' && window.location.port !== '443' && window.location.port !== '';
  if (isLocal) {
    window.__env.API_BASE_URL = '${API_BASE_URL}';
    window.__env.API_URL = '${API_URL}';
    window.__env.BIOMETRIC_WEBHOOK_URL = '${BIOMETRIC_WEBHOOK_URL}';
  } else {
    var origin = (typeof window !== 'undefined' && window.location && window.location.origin) ? window.location.origin : '${API_BASE_URL}';
    window.__env.API_BASE_URL = origin;
    window.__env.API_URL = origin + '/api';
    window.__env.BIOMETRIC_WEBHOOK_URL = origin + '/api/attendance/biometric/hikvision';
  }
}(this));
`;

const envJsPath = path.join(__dirname, '..', 'src', 'assets', 'env.js');
fs.writeFileSync(envJsPath, envJsContent, 'utf8');

// 4. Generate src/environments/environment.ts
const envTsContent = `/**
 * Global IMSERP Environment Configuration
 * Auto-generated by scripts/set-env.js from .env file
 */
export const environment = {
  production: false,
  apiBaseUrl: (typeof window !== 'undefined' && (window as any).__env?.API_BASE_URL) || '${API_BASE_URL}',
  apiUrl: (typeof window !== 'undefined' && (window as any).__env?.API_URL) || '${API_URL}',
  biometricWebhookUrl: (typeof window !== 'undefined' && (window as any).__env?.BIOMETRIC_WEBHOOK_URL) || '${BIOMETRIC_WEBHOOK_URL}'
};
`;

const envTsPath = path.join(__dirname, '..', 'src', 'environments', 'environment.ts');
fs.writeFileSync(envTsPath, envTsContent, 'utf8');

// 5. Generate src/environments/environment.prod.ts
const envProdTsContent = `/**
 * Production IMSERP Environment Configuration
 * Auto-generated by scripts/set-env.js from .env file
 */
export const environment = {
  production: true,
  apiBaseUrl: (typeof window !== 'undefined' && (window as any).__env?.API_BASE_URL) || '${API_BASE_URL}',
  apiUrl: (typeof window !== 'undefined' && (window as any).__env?.API_URL) || '${API_URL}',
  biometricWebhookUrl: (typeof window !== 'undefined' && (window as any).__env?.BIOMETRIC_WEBHOOK_URL) || '${BIOMETRIC_WEBHOOK_URL}'
};
`;

const envProdTsPath = path.join(__dirname, '..', 'src', 'environments', 'environment.prod.ts');
fs.writeFileSync(envProdTsPath, envProdTsContent, 'utf8');

console.log(`[IMSERP ENV] Successfully updated environment.ts, environment.prod.ts, and assets/env.js`);
