-- Idempotent script to support Coaching Batch Migration & Roll-over in StudentPromotionHistories

IF EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'StudentPromotionHistories' AND COLUMN_NAME = 'FromClassId' AND IS_NULLABLE = 'NO')
BEGIN
    ALTER TABLE StudentPromotionHistories ALTER COLUMN FromClassId UNIQUEIDENTIFIER NULL;
END

IF EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'StudentPromotionHistories' AND COLUMN_NAME = 'ToClassId' AND IS_NULLABLE = 'NO')
BEGIN
    ALTER TABLE StudentPromotionHistories ALTER COLUMN ToClassId UNIQUEIDENTIFIER NULL;
END

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'StudentPromotionHistories' AND COLUMN_NAME = 'FromBatchId')
BEGIN
    ALTER TABLE StudentPromotionHistories ADD FromBatchId UNIQUEIDENTIFIER NULL;
END

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'StudentPromotionHistories' AND COLUMN_NAME = 'ToBatchId')
BEGIN
    ALTER TABLE StudentPromotionHistories ADD ToBatchId UNIQUEIDENTIFIER NULL;
END

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'StudentPromotionHistories' AND COLUMN_NAME = 'Scope')
BEGIN
    ALTER TABLE StudentPromotionHistories ADD Scope NVARCHAR(50) NULL DEFAULT 'School';
END
